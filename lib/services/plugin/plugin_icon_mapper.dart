  static String? canonicalName(String name) {
    final normalized = normalize(name);
    return icons.containsKey(normalized) ? normalized : null;
  }

  /// Canonical name, warning and falling back to `extension` when invalid.
  static String sanitizeName(String name) {
    final canonical = canonicalName(name);
    if (canonical != null) return canonical;
    warnInvalid(name);
    return 'extension';
  }

  /// Emits the standard warning for an invalid or unsupported icon name.
  static void warnInvalid(String name) {
    final rendered = "非法或不支持的图标名称：'$name'，请使用全小写蛇形命名（如 'home', 'settings'）。";
    debugPrint('[Plugins] $rendered');
    LauncherLog.warning('Plugins', rendered);
  }

  /// Normalises camelCase, spaces, hyphens, the optional `Icons.` prefix and
  /// the `material:` library prefix. Returns an empty string for other
  /// libraries or malformed names.
  static String normalize(String name) {
    var value = name.trim();
    if (value.toLowerCase().startsWith('icons.')) {
      value = value.substring('Icons.'.length);
    }
    final colon = value.indexOf(':');
    if (colon >= 0) {
      final library = value.substring(0, colon).trim().toLowerCase();
      if (library != 'material') return '';
      value = value.substring(colon + 1).trim();
      if (value.toLowerCase().startsWith('icons.')) {
        value = value.substring('Icons.'.length);
      }
    }
    if (value.contains(':')) return '';
    value = value.replaceAllMapped(
      RegExp(r'([a-z0-9])([A-Z])'),
      (match) => '${match[1]}_${match[2]}',
    );
    return value
        .replaceAll(RegExp(r'[\s\-]+'), '_')
        .replaceAll(RegExp(r'_+'), '_')
        .replaceAll(RegExp(r'^_+|_+$'), '')
        .toLowerCase();
  }
